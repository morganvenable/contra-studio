// Parse retained ContraDB snapshots into stored next-engine dances.
// node --experimental-strip-types scripts/next-store-dance.mjs 2321 [more ids]
// node --experimental-strip-types scripts/next-store-dance.mjs --supported
//   stores every Ready dance that parses and passes the corpus check, and
//   rewrites src/next/dances/index.ts to list the stored dances.
import { readdirSync, writeFileSync } from 'node:fs';
import { READY_LIBRARY } from '../src/ready-library.ts';
import { compileNext } from '../src/next/dance.ts';
import { verifyDance } from '../src/next/core/verify.ts';
import { buildStored, firstUnparsed } from './next-dances.mjs';

const write = (id, stored) =>
  writeFileSync(`src/next/dances/${id}.json`, JSON.stringify(stored, null, 2) + '\n');

const args = process.argv.slice(2);
if (args[0] === '--supported') {
  const seen = new Set();
  for (const { id } of READY_LIBRARY) {
    if (seen.has(id) || firstUnparsed(id) !== undefined) continue;
    seen.add(id);
    let stored;
    try {
      stored = buildStored(id);
    } catch {
      continue;
    }
    const verdict = verifyDance(stored, compileNext);
    if (verdict.ok) write(id, stored);
    const note = verdict.ok ? '' : ` -- ${verdict.problem}`;
    console.log(`${verdict.ok ? 'stored' : 'skipped'} ${id} ${stored.title}${note}`);
  }
} else {
  for (const id of args) {
    if (!/^\d+$/.test(id))
      throw new Error('Usage: next-store-dance.mjs <contradb id>... | --supported');
    write(id, buildStored(id));
    console.log(`Wrote src/next/dances/${id}.json`);
  }
}

// The index lists every stored dance so the app and tests load them all.
const ids = readdirSync('src/next/dances')
  .filter((f) => /^\d+\.json$/.test(f))
  .map((f) => f.slice(0, -5))
  .sort((a, b) => Number(a) - Number(b));
const lines = [
  '// Generated by scripts/next-store-dance.mjs: every stored next-engine dance.',
  "import type { StoredDance } from '../dance.ts';",
  ...ids.map((id) => `import d${id} from './${id}.json' with { type: 'json' };`),
  '',
  'export const STORED: readonly StoredDance[] = [',
  ...ids.map((id) => `  d${id} as StoredDance,`),
  '];',
  '',
];
writeFileSync('src/next/dances/index.ts', lines.join('\n'));
console.log(`Index lists ${ids.length} dances.`);
