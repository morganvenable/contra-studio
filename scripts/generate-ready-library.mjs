// Generate local, review-complete source archives. No network or source rewriting.
// Run: node scripts/generate-ready-library.mjs
// Optional --assemble-unchanged copies exact unchanged archives without issuing
// current motion evidence. Mandatory full Ready CI still checks every entry.
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {REVIEWED_SOURCE_IDS,SOURCE_LIBRARY} from '../src/source-library.ts';
import {READY_LIBRARY} from '../src/ready-library.ts';
import {assembleUnchangedReadyEntry} from './assemble-unchanged-ready.mjs';
import {prepareReadyArchive} from './prepare-ready-archive.mjs';
import {readReviewedArchive} from './read-reviewed-archive.mjs';
import {readContraDbImport} from '../src/contradb-import.ts';
import {readContraDbSource,makeContraDbSnapshot} from '../src/contradb-source.ts';
import {compileChoreography} from '../src/choreography.ts';
const args=process.argv.slice(2);
if(args.some(arg=>arg!=='--assemble-unchanged'))throw Error('Unknown generator option');
const assembleUnchanged=args.includes('--assemble-unchanged');
if(assembleUnchanged)console.log('Assembly mode: reused entries require current full Ready motion CI before release.');
const root=path.resolve(import.meta.dirname,'..'),entries=[],evidence=[],priorEntries=new Map(READY_LIBRARY.map(entry=>[entry.id,entry]));
for(const id of REVIEWED_SOURCE_IDS){
 const raw=await readFile(path.join(root,'test-data/contradb',id+'.json'),'utf8');
 const parsedSource=readContraDbSource(raw),original=parsedSource.record;if(!original||!parsedSource.structurallyValid)throw Error('Unreadable source '+id);
 const reviewed=readReviewedArchive(original),card=SOURCE_LIBRARY.find(item=>item.id===id);
 const assembled=assembleUnchanged?assembleUnchangedReadyEntry(original,priorEntries.get(id),reviewed,card):undefined;
 if(assembled){entries.push(assembled);evidence.push({id,sourceSnapshotId:original.snapshotId,archiveSha256:createHash('sha256').update(assembled.archive).digest('hex'),status:'assembled-current-motion-pending'});console.log('Assembled (current motion pending) '+id+' '+original.title);continue;}
 const prepared=prepareReadyArchive(raw,original,reviewed??priorEntries.get(id)),result=prepared.result;
 if(!result.dance||!result.coverage.executable)throw Error('Reviewed source is not executable '+id+': '+result.errors.join('; '));
 const archive=prepared.archive,saved=JSON.parse(archive);
 if(saved.schema!=='contra-studio/contradb-interpretation'||saved.sourceSnapshotId!==original.snapshotId)throw Error('Missing exact archive '+id);
 if(JSON.stringify(saved.snapshot)!==JSON.stringify(makeContraDbSnapshot(original)))throw Error('Saved source differs '+id);
 const replay=prepared.replayed?result:readContraDbImport(archive);
 if(!replay.dance||!replay.coverage.executable)throw Error('Archive replay failed '+id);
 if(JSON.stringify(replay.dance)!==JSON.stringify(result.dance))throw Error('Archive changes interpretation '+id);
 const compiled=compileChoreography(replay.dance,6);
 if(compiled.totalBeats!==64)throw Error('Unexpected count budget '+id);
 for(const beat of[0,1,15.5,32,63.999,64,127.5]){
  const frame=compiled.sample(beat);if(!frame.poses.length||frame.poses.some(p=>!Number.isFinite(p.position.x+p.position.z+p.yaw)))throw Error('Invalid playable frame '+id);
 }
 if(card&&(card.title!==original.title||card.author!==original.author))throw Error('Library identity mismatch '+id);
 entries.push({id,title:original.title,author:original.author,formation:card?.formation??original.formation,archive});
 evidence.push({id,sourceSnapshotId:original.snapshotId,archiveSha256:createHash('sha256').update(archive).digest('hex'),...(assembleUnchanged?{status:'current-motion-checked'}:{})});
 console.log('Ready '+id+' '+original.title);
}
const content=`// Generated by scripts/generate-ready-library.mjs. Exact reviewed source archives.\n// Opening these entries never requires an upstream download.\nexport interface ReadyLibraryEntry {readonly id:string;readonly title:string;readonly author:string;readonly formation:string;readonly archive:string;}\nexport const READY_LIBRARY:readonly ReadyLibraryEntry[]=Object.freeze(${JSON.stringify(entries)}.map(entry=>Object.freeze(entry)));\n`;
await writeFile(path.join(root,'src/ready-library.ts'),content);
await writeFile(path.join(root,'qa/ready-library-generation.json'),JSON.stringify({count:entries.length,entries:evidence},null,2)+'\n');
console.log(`Generated ${entries.length} reviewed local archives (${Buffer.byteLength(content)} bytes).`);
